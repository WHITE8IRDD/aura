export const ALL_CHARS: UnicodeChar[] = [...ALL, ...ALL2, ...ALL3]

export function getCharsByCategory(category: string): UnicodeChar[] {
  return ALL_CHARS.filter(c => c.category === category)
}

export function searchChars(query: string): UnicodeChar[] {
  const q = query.toLowerCase().trim()
  if (!q) return []
  return ALL_CHARS.filter(c =>
    c.name.toLowerCase().includes(q) ||
    c.char.includes(q) ||
    c.code.toLowerCase().includes(q)
  ).slice(0, 100)
}
