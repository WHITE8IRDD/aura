export interface UnicodeChar {
  char: string
  name: string
  code: string
  category: string
  subcategory?: string
}

function ch(char: string, name: string, _aliases: string[], category: string, subcategory: string): UnicodeChar {
  const cp = char.codePointAt(0)!
  return { char, name, code: `U+${cp.toString(16).toUpperCase().padStart(4, '0')}`, category, subcategory }
}

